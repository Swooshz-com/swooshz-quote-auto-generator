def _operation(op, schemas, media_types):
    parameters = [{"name": key, "in": "path", "required": True,
                   "schema": {"type": "string", "enum": list(field.enum)} if field.enum else _ref("Id")}
                  for key, field in op.path_params]
    if op.method == "POST":
        parameters.append(_ref("IdempotencyKey", "parameters"))
    if op.kind == "job":
        success = ("202", {"description": "Accepted durably", "headers": {
            **_NO_STORE, "Location": {"schema": _ref("Link")}, "Retry-After": {"schema": {"type": "integer", "minimum": 2}}}})
    elif op.response_schema:
        success = ("200", {"description": "Safe resource view", "headers": dict(_NO_STORE)})
    else:
        success = ("200", {"description": "Verified bytes; same estimate policy as JSON", "headers": dict(_NO_STORE),
                           "content": {media: {"schema": {"type": "string", "format": "binary"}}
                                       for media in media_types.values()}})
    if op.response_schema:
        success[1]["content"] = {"application/json": {
            "schema": _ref(op.response_schema), "example": schemas[op.response_schema]["examples"][0]}}
    responses = {success[0]: success[1]}
    responses.update({status: _ref(f"Error{status}", "responses") for status in error_status_codes()})
    result = {"summary": op.summary, "parameters": parameters, "responses": responses,
              "x-reject-unknown-query": True, "x-query-schema": _ref("EmptyQuery")}
    if op.method == "POST":
        body = _ref(op.request_schema)
        if op.staff_request_schema:
            body = {"oneOf": [body, _ref(op.staff_request_schema)], "description": _PRICE_UNION_NOTE}
        result["requestBody"] = {"required": True, "content": {"application/json": {
            "schema": body, "example": schemas[op.request_schema]["examples"][0]}}}
        result["x-staff-mutation-security"] = [{"StaffSession": [], "StaffCsrf": []}]
    if op.description:
        result["description"] = op.description
    if op.staff_request_schema:
        result["x-auth-request-schemas"] = {"ServiceCredential": _ref(op.request_schema),
                                            "StaffSession": _ref(op.staff_request_schema)}
    result.update({"operationId": op.name, "x-scope": op.scope, "x-audiences": sorted(op.audiences),
                   "x-caller-policies": sorted(op.caller_policies), "x-stability": op.stability})
    return result


