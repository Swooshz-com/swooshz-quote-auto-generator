def _error_body(codes):
    return {"type": "object", "additionalProperties": False, "properties": {
        "code": {"type": "string", "enum": list(codes)},
        "message": {"type": "string", "minLength": 1, "maxLength": 256},
        "reference": {"type": "string", "pattern": "^ERR-[0-9A-F]{8}" + _END},
        "retryable": {"type": "boolean"},
    }, "required": ["code", "message", "reference", "retryable"]}


def error_status_codes():
    """{status: [codes]} in status order, codes in table order."""
    table = {}
    for code, status in ERROR_STATUS.items():
        table.setdefault(str(status), []).append(code)
    return dict(sorted(table.items()))


def _error_responses():
    retry = {"Retry-After": {"schema": {"type": "integer", "minimum": 1}}}
    return {f"Error{status}": {
        "description": ", ".join(codes),
        "headers": {**_NO_STORE, **(retry if int(status) in RETRY_AFTER_STATUSES else {})},
        "content": {"application/json": {"schema": {
            "type": "object", "additionalProperties": False,
            "properties": {"error": _error_body(codes)}, "required": ["error"]}}},
    } for status, codes in error_status_codes().items()}


def _string_list(item_max=256, count=32):
    return {"type": "array", "items": {"type": "string", "minLength": 1, "maxLength": item_max}, "maxItems": count}


def _quantity():
    return {"anyOf": [{"type": "number", "exclusiveMinimum": 0}, {"type": "null"}]}


def _unit():
    # Customer output says sqm, never m2.
    return {"anyOf": [{"type": "string", "maxLength": 32, "pattern": "^(?!m2$).+" + _END}, {"type": "null"}]}


def _nullable(name):
    return {"anyOf": [_ref(name), {"type": "null"}]}


